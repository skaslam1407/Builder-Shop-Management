function interpolate(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : `{${key}}`,
  );
}

let activeLanguage: LanguageCode = "en";

export function setActiveLanguage(language: LanguageCode): void {
  activeLanguage = language;
}

export function t(
  key: string,
  vars?: Record<string, string | number>,
): string {
  return translate(activeLanguage, key, vars);
}

export function translate(
  language: LanguageCode,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const text = language === "bn" ? bn[key] ?? key : key;
  return interpolate(text, vars);
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const language = useAuthStore((state) => state.user?.language ?? "en");
  return useMemo(() => (key: string, vars?: Record<string, string | number>) => translate(language, key, vars), [language]);
}

export function localeFor(language: LanguageCode): string {
  return language === "bn" ? "bn-IN" : "en-IN";
}
